"""Generate the standalone import from the shared JS and YAML. Requires PyYAML."""
import argparse
import copy
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail when either published JS needs regeneration')
args = parser.parse_args()
base = yaml.safe_load((ROOT / 'linkcube-generic-merge.yaml').read_text(encoding='utf-8'))
source = (ROOT / 'linkcube-generic.js').read_text(encoding='utf-8')
wrapper = '''
// Apply the companion YAML before the shared routing transform.
// Unsupported subscriptions retain the shared script's unchanged-input behavior.
const flclashRoutingMain = config => transform(config, FLCLASH_PROFILE);
main = function(config) {
  if (!config || typeof config !== "object" || !Array.isArray(config.proxies)
      || (config["proxy-providers"] && Object.keys(config["proxy-providers"]).length)
      || !config.proxies.some((proxy) => proxy && isRealNode(proxy.name))) {
    return flclashRoutingMain(config);
  }
  const copied = JSON.parse(JSON.stringify(config));
  const defaults = JSON.parse(JSON.stringify(FLCLASH_BASE));
  const prepared = Object.assign({}, copied, defaults);
  for (const key of ["profile", "tun", "dns"]) {
    prepared[key] = Object.assign({}, copied[key] || {}, defaults[key]);
  }
  const previousDns = copied.dns || {};
  prepared.dns["nameserver-policy"] = Object.assign({},
    defaults.dns["nameserver-policy"], previousDns["nameserver-policy"] || {});
  const filterMode = previousDns["fake-ip-filter-mode"] || "blacklist";
  prepared.dns["fake-ip-filter-mode"] = filterMode;
  const previousFilter = Array.isArray(previousDns["fake-ip-filter"])
    ? previousDns["fake-ip-filter"] : [];
  prepared.dns["fake-ip-filter"] = filterMode === "blacklist"
    ? Array.from(new Set(previousFilter.concat(defaults.dns["fake-ip-filter"])))
    : previousFilter.slice();
  return flclashRoutingMain(prepared);
};
'''
profiles = {
    'desktop': ('flclash-single.js', {}, {}),
    'mobile': ('flclash-mobile.js',
               {'autoInterval': 900, 'ruleInterval': 172800, 'gameInterval': 86400},
               {'unified-delay': False, 'geo-update-interval': 72}),
}
stale = []
for name, (filename, routing, settings) in profiles.items():
    profile_base = copy.deepcopy(base)
    profile_base.update(settings)
    content = f'// Generated by scripts/build_flclash.py; {name} profile. Import this file alone in FlClash.\n'
    content += '// Contains no nodes or credentials. Client settings can override script output.\n'
    content += source.rstrip() + '\n\nconst FLCLASH_PROFILE = Object.assign({}, DESKTOP_PROFILE, '
    content += json.dumps(routing) + ');\nconst FLCLASH_BASE = '
    content += json.dumps(profile_base, ensure_ascii=False, indent=2) + ';\n' + wrapper
    target = ROOT / filename
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            stale.append(filename)
    else:
        target.write_text(content, encoding='utf-8')
        print('Generated ' + filename)
if stale:
    raise SystemExit(', '.join(stale) + ' is stale; run python scripts/build_flclash.py')
if args.check:
    print('Both standalone scripts match shared sources')
