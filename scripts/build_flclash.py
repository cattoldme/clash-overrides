"""Generate the standalone import from the shared JS and YAML. Requires PyYAML."""
import argparse
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail when the published JS needs regeneration')
args = parser.parse_args()
base = yaml.safe_load((ROOT / 'linkcube-generic-merge.yaml').read_text(encoding='utf-8'))
source = (ROOT / 'linkcube-generic.js').read_text(encoding='utf-8')
wrapper = '''
// Apply the companion YAML before the shared routing transform.
// Unsupported subscriptions retain the shared script's unchanged-input behavior.
const flclashRoutingMain = main;
main = function(config) {
  if (!config || typeof config !== "object" || !Array.isArray(config.proxies)
      || (config["proxy-providers"] && Object.keys(config["proxy-providers"]).length)
      || !config.proxies.some((proxy) => proxy && isRealNode(proxy.name))) {
    return flclashRoutingMain(config);
  }
  const prepared = JSON.parse(JSON.stringify(config));
  const defaults = JSON.parse(JSON.stringify(FLCLASH_BASE));
  Object.assign(prepared, defaults);
  for (const key of ["profile", "tun", "dns"]) {
    prepared[key] = Object.assign({}, config[key] || {}, defaults[key]);
  }
  const previousDns = config.dns || {};
  prepared.dns["nameserver-policy"] = Object.assign({},
    defaults.dns["nameserver-policy"], previousDns["nameserver-policy"] || {});
  const filterMode = previousDns["fake-ip-filter-mode"] || "blacklist";
  prepared.dns["fake-ip-filter-mode"] = filterMode;
  const previousFilter = Array.isArray(previousDns["fake-ip-filter"])
    ? previousDns["fake-ip-filter"] : [];
  prepared.dns["fake-ip-filter"] = filterMode === "blacklist"
    ? Array.from(new Set(previousFilter.concat(defaults.dns["fake-ip-filter"])))
    : previousFilter.slice();
  return flclashRoutingMain(prepared);
};
'''
content = '// Generated by scripts/build_flclash.py; import this file alone in FlClash.\n'
content += '// Contains no nodes or credentials. Client settings can override script output.\n'
content += source.rstrip() + '\n\nconst FLCLASH_BASE = ' + json.dumps(base, ensure_ascii=False, indent=2) + ';\n' + wrapper
target = ROOT / 'flclash-single.js'
if args.check:
    if not target.exists() or target.read_text(encoding='utf-8') != content:
        raise SystemExit('flclash-single.js is stale; run python scripts/build_flclash.py')
    print('Standalone script matches shared sources')
else:
    target.write_text(content, encoding='utf-8')
    print('Generated flclash-single.js')
